/** Ищет самое длинное совпадение первым, чтобы «Новороссийск» не подходил
 * раньше «Ростов-на-Дону» и т.п. по частичной подстроке. */
function findLongestMatch(text: string, dict: Record<string, string>): { key: string; value: string } | null {
  const keys = Object.keys(dict).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (text.includes(key)) return { key, value: dict[key] };
  }
  return null;
}

export function approximateLocation(raw: string | null): { country: string; city: string | null } | null {
  if (!raw) return null;
  for (const [flag, country] of Object.entries(FLAG_EMOJI_COUNTRY)) {
    if (raw.includes(flag)) return { country, city: null };
  }
  const text = raw.toLowerCase();
  const countryHit = findLongestMatch(text, COUNTRY_TOKENS);
  if (countryHit) return { country: countryHit.value, city: null };
  const cityHit = findLongestMatch(text, CITY_TO_COUNTRY);
  if (cityHit) return { country: cityHit.value, city: cityHit.key };
  return null;
}

