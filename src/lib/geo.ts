/** Равнопромежуточная (equirectangular) проекция шир./долг. в проценты
 * x/y условного прямоугольника карты — не претендует на точную картографию,
 * только на «где на мире примерно находится эта страна». */
export function projectToPercent(lat: number, lon: number): { xPct: number; yPct: number } {
  return {
    xPct: ((lon + 180) / 360) * 100,
    yPct: ((90 - lat) / 180) * 100,
  };
}
