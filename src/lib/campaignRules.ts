/**
 * Round 76 — «с этой рекламной кампании сразу распределять заявки на воркшоп
 * 06.11» (Anastasiia, 19 окт 2026). Лиды из лид-формы Meta приходят в CRM
 * только с названием кампании (utm_campaign) — без продукта и потока.
 * Правило «кампания → продукт + поток» (таблица campaign_lead_rules) говорит
 * CRM, куда класть такие заявки.
 */

/** Ключ для сравнения названий кампаний: Meta/мост могут отдать двойной
 * пробел («15/10 |  МК Светлана»), разный регистр или пробелы по краям. */
export function campaignKey(name: string | null | undefined): string {
  return (name ?? "").replace(/\s+/g, " ").trim().toLowerCase();
}
